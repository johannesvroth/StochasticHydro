#!/usr/bin/env python3
r"""Compute the zero-momentum stress autocorrelator, the Green-Kubo kernel of
the shear viscosity,

    G(t) = (1/V) sum_T Pi_xy(T) Pi_xy(T+t),    Pi_ab(T) = sum_x j_a j_b / rho,

from the raw real-space jx.dat, jy.dat, jz.dat snapshot files of one or more
run directories, where each row is one time step and each column is a lattice
site idx = nx*Ny*Nz + ny*Nz + nz (nx slowest, nz fastest). V = Nx Ny Nz in
units of the lattice spacing. Pi_ab is the convective (ideal) stress
rho v_a v_b at k = 0; the viscous stress has no k = 0 component and the noise
is white, so for t > 0 G(t) is the full Green-Kubo kernel and
eta = (1/T) int_0^inf G(t) dt.

Two estimates are written, which agree for an isotropic fluid:

  G_offdiag: average over the off-diagonal components xy, yz, zx,
  G_diag:    average over the traceless diagonal combinations
             (Pi_xx - Pi_yy)/2 and (Pi_xx + Pi_yy - 2 Pi_zz)/(2 sqrt 3),
             which carry the same normalization as Pi_xy.

On the cubic lattice the two belong to different irreducible representations,
so they may differ at short times; the long-time tail is an infrared effect
and should be the same in both.

For two Gaussian transverse diffusive modes the long-time tail is

    G(t) = (7/15) T^2 (8 pi nu_R t)^(-3/2),    nu_R = eta_R/rho,

cut off at t ~ 1/(2 nu_R k_min^2) by the finite box.

Run directories are expected to be named as generated by sim, e.g.
sim-Nx8Ny8Nz8dt0.1eta0.1Lam1.25seed327271822; Nx, Ny, Nz and dt are parsed
from the name. Unless --output-dir is passed, each correlator is written to a
directory named like the run but with "sim" replaced by "stress-time-corr"
and the seed stripped (e.g. stress-time-corr-Nx8Ny8Nz8dt0.1eta0.1Lam1.25). A
trailing "x" suffix on the run name (written by sim for --no-ideal-step runs)
is kept at the very end.

The snapshot files are read row by row, so memory use does not grow with the
length of the run. Runs that were interrupted (or are still running) end in a
partially written row; such rows are ignored, and all three files are
truncated to the time steps that are complete in every file.

For each run directory, writes a file <output-dir>/<run_name>.dat with
columns time_diff, G_offdiag, G_diag and a header recording nx, ny, nz, dt
and the mass density."""

import argparse
import re
from pathlib import Path

import numpy as np

FLOAT = r"[0-9.]+(?:[eE][+-]?[0-9]+)?"
RUN_NAME_RE = re.compile(
    rf"sim-Nx(?P<nx>\d+)Ny(?P<ny>\d+)Nz(?P<nz>\d+)"
    rf"dt(?P<dt>{FLOAT})eta(?P<eta>{FLOAT})Lam(?P<lam>{FLOAT})"
    rf"seed(?P<seed>\d+)(?P<suffix>x?)$"
)


def parse_run_name(run_dir: Path) -> dict:
    m = RUN_NAME_RE.match(run_dir.name)
    if m is None:
        raise SystemExit(f"Cannot parse run directory name '{run_dir.name}': "
                         "expected the form sim-Nx8Ny8Nz8dt0.1eta0.1Lam1.25seed123")
    return {"nx": int(m["nx"]), "ny": int(m["ny"]), "nz": int(m["nz"]),
            "dt": float(m["dt"]), "suffix": m["suffix"],
            "out_base": re.sub(r"^sim", "stress-time-corr",
                               re.sub(r"seed\d+x?$", "", run_dir.name))}


def complete_rows(path: Path, ncols: int):
    """Yield the rows of path that contain all ncols values.

    sim writes one space after every value, so a complete row contains exactly
    ncols spaces. A run that was killed while writing (or that is still
    running) leaves a partially written final row; stop at the first such
    row."""
    with open(path) as f:
        for lineno, line in enumerate(f, 1):
            nvalues = line.count(" ")
            if nvalues != ncols:
                print(f"warning: {path}: row {lineno} holds {nvalues} of "
                      f"{ncols} values, ignoring it and everything after it")
                return
            yield line


def stress_series(run_dir: Path, nx: int, ny: int, nz: int,
                  mass_density: float) -> np.ndarray:
    """Return Pi_ab(T) = sum_x j_a j_b / rho for every complete time step, as
    an array of shape (n_steps, 3, 3)."""
    nsites = nx * ny * nz
    rows = zip(*(complete_rows(run_dir / f"j{c}.dat", nsites) for c in "xyz"))
    stress = []
    for row in rows:
        j = np.stack([np.fromstring(line, sep=" ") for line in row])
        stress.append(j @ j.T / mass_density)
    return np.array(stress).reshape(-1, 3, 3)


def time_correlator(a: np.ndarray) -> np.ndarray:
    """sum_T a(T) a(T+t) / (n - t) for every t = 0..n-1, via zero-padded FFT
    (identical to the direct sum, without the O(n^2) cost)."""
    n = len(a)
    f = np.fft.rfft(a, 2 * n)
    return np.fft.irfft(f * np.conj(f), 2 * n)[:n] / (n - np.arange(n))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--run-dirs", type=Path, nargs="+", required=True,
                         help="One or more run directories, each containing its own "
                              "jx.dat, jy.dat, jz.dat, named as generated by sim "
                              "(e.g. sim-Nx8Ny8Nz8dt0.1eta0.1Lam1.25seed123)")
    parser.add_argument("--mass-density", type=float, default=1.0, help="Mass density")
    parser.add_argument("--output-dir", type=Path, default=None,
                         help="Directory to write the computed correlators into "
                              "(default: run dir name with 'sim' replaced by "
                              "'stress-time-corr' and the seed stripped)")
    args = parser.parse_args()

    for run_dir in args.run_dirs:
        params = parse_run_name(run_dir)
        nx, ny, nz = params["nx"], params["ny"], params["nz"]

        output_dir = (args.output_dir if args.output_dir is not None
                      else Path(f"{params['out_base']}{params['suffix']}"))
        output_dir.mkdir(parents=True, exist_ok=True)

        stress = stress_series(run_dir, nx, ny, nz, args.mass_density)
        n_steps = len(stress)
        if n_steps == 0:
            raise SystemExit(f"{run_dir}: no complete time steps found")

        offdiag = [stress[:, 0, 1], stress[:, 1, 2], stress[:, 2, 0]]
        diag = [(stress[:, 0, 0] - stress[:, 1, 1]) / 2,
                (stress[:, 0, 0] + stress[:, 1, 1] - 2 * stress[:, 2, 2]) / (2 * np.sqrt(3))]

        volume = nx * ny * nz
        g_offdiag = sum(time_correlator(c) for c in offdiag) / len(offdiag) / volume
        g_diag = sum(time_correlator(c) for c in diag) / len(diag) / volume

        time_diff = np.arange(n_steps) * params["dt"]

        header = (f"nx={nx} ny={ny} nz={nz} dt={params['dt']} "
                  f"mass_density={args.mass_density}\n"
                  "time_diff G_offdiag G_diag")
        out_path = output_dir / f"{run_dir.name}.dat"
        np.savetxt(out_path, np.column_stack([time_diff, g_offdiag, g_diag]),
                   header=header)
        print(f"Wrote {out_path} ({n_steps} time steps)")


if __name__ == "__main__":
    main()
