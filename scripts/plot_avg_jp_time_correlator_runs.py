#!/usr/bin/env python3
"""Plot the time correlator sum_T jpx(t)*jpx(t+T) as a function of the time
difference t, one curve per run.

Same data and the same axes as plot_avg_jp_time_correlator.py, which shows
the mean over the runs with an error band; this script draws the runs
themselves instead. Use it to see the run-to-run scatter directly: how far
apart the runs are at a given t, whether one of them is an outlier, and where
each run first decays into the noise and crosses zero -- the point past which
that run no longer contributes anything to a log-derivative.

Reads the per-run correlator files written by compute_jpx_time_correlator.py:
one <run>.dat file per run in --input-dir, with columns time_diff, Re, Im and
a header recording nx, ny, nz, nkx, nky, nkz, dt for the given mode. Runs of
different length are each drawn over their own t, not cut to the shortest.

Each input directory is expected to be named as generated by
compute_jpx_time_correlator.py, e.g. avg-jp-time-corr-Nx8Ny8Nz8dt0.1eta0.1Lam1.25nk7 (with
an optional trailing "x" for --no-ideal-step runs); the shear viscosity eta
is parsed from that name. With several directories, all of their runs are
drawn into the same plot.

By default the runs of one directory share that directory's color and the
legend has one entry per directory, giving the number of runs behind it: a
legend of one entry per run is unreadable, and the point of the default view
is the width of the band the runs span, not which run is which. With
--label-runs every run gets its own color and its own legend entry, labelled
by the seed parsed from its file name, so that an outlier can be identified;
that only makes sense for one directory at a time. One legend entry per run
does not fit next to the curves, so in that mode the figure is widened and
the legend moved out of the axes, to the right of them.

The t axis is scaled by the bare correlation time of the mode,
tau = rho/(eta (1+eta_reg_uv) k_hat^2), so that the bare exponential decay
reaches 1/e at t/tau = 1 for every eta and k and curves from different
directories can be compared directly."""

import argparse
import re
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

import plot_style
from rfrg_coefficients import coefficients

plot_style.use()

AUTO_OUTPUT = Path("<auto>")

FLOAT = r"[0-9.]+(?:[eE][+-]?[0-9]+)?"
OBS_NAME_RE = re.compile(
    rf"avg-jp-time-corr-Nx(?P<nx>\d+)Ny(?P<ny>\d+)Nz(?P<nz>\d+)"
    rf"dt(?P<dt>{FLOAT})eta(?P<eta>{FLOAT})Lam(?P<lam>{FLOAT})nk(?P<nk>\d+)(?P<suffix>x?)$"
)
SEED_RE = re.compile(r"seed(\d+)")


def parse_obs_name(input_dir: Path) -> dict:
    m = OBS_NAME_RE.match(input_dir.name)
    if m is None:
        raise SystemExit(f"Cannot parse input directory name '{input_dir.name}': "
                         "expected the form avg-jp-time-corr-Nx8Ny8Nz8dt0.1eta0.1Lam1.25nk7")
    return {"nx": int(m["nx"]), "ny": int(m["ny"]), "nz": int(m["nz"]),
            "dt": float(m["dt"]), "eta": float(m["eta"]), "lam": float(m["lam"]),
            "nk": int(m["nk"])}


def lattice_label(nx: int, ny: int, nz: int) -> str:
    r"""LaTeX for the lattice size: $32^3$ for a cubic lattice, $32^2 \times 10$
    when one direction differs from the two others."""
    dims = (nx, ny, nz)
    if nx == ny == nz:
        return rf"${nx}^3$"
    for d in dims:
        if dims.count(d) == 2:
            odd = next(o for o in dims if o != d)
            return rf"${d}^2 \times {odd}$"
    return rf"${nx} \times {ny} \times {nz}$"


def legend_label(input_dir: Path, with_nk: bool = False) -> str:
    r"""Legend entry for one directory, e.g.
    "$32^3$, dt = 10, $\eta = 0.0707107$, $\Lambda = 0.4$".

    The numbers are taken verbatim from the directory name, so the legend
    shows exactly what the run used. The mode index is appended only when
    asked for, i.e. when the directories do not share one and the y label
    cannot carry it, and --no-ideal-step runs are marked as such; without
    that two directories differing only in nk (or in the trailing "x") would
    get the same legend entry."""
    m = OBS_NAME_RE.match(input_dir.name)
    label = (f"{lattice_label(int(m['nx']), int(m['ny']), int(m['nz']))}, "
             #f"dt = {m['dt']}, "
             rf"$\eta = {m['eta']}$, $\Lambda = {m['lam']}$")
    if with_nk:
        label += rf", $n_k = {m['nk']}$"
    if m["suffix"] == "x":
        label += ", no ideal step"
    return label


def run_label(path: Path) -> str:
    """Legend entry for a single run: its seed, which is the only part of the
    file name that distinguishes the runs of one directory. Files that do not
    carry a seed fall back to their stem."""
    m = SEED_RE.search(path.stem)
    return f"seed {m.group(1)}" if m else path.stem


def run_colors(n: int):
    """n colors for the runs of one directory, sampled from turbo.

    Not the default property cycle: it holds ten colors, and a plot of
    fifteen runs would silently give two of them the same one. The extreme
    ends of the map are left out, where it goes very dark."""
    return plt.get_cmap("turbo")(np.linspace(0.05, 0.95, n))


def read_header(path: Path) -> dict:
    with open(path) as f:
        first_line = f.readline().lstrip("#").strip()
    return {key: float(value) for key, value in
            (item.split("=") for item in first_line.split())}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input_dirs", type=Path, nargs="+",
                         help="One or more directories containing the *.dat correlator "
                              "files written by compute_jpx_time_correlator.py, named "
                              "like avg-jp-time-corr-Nx8Ny8Nz8dt0.1eta0.1Lam1.25nk7 (eta is "
                              "parsed from the name); all are drawn into the same plot")
    parser.add_argument("--mass-density", type=float, default=1.0, help="Mass density")
    parser.add_argument("--temp", type=float, default=1.0, help="Temperature")
    parser.add_argument("--label-runs", action="store_true",
                         help="Give every run its own color and its own legend "
                              "entry, labelled by its seed, instead of one color "
                              "and one entry per directory; for identifying a "
                              "single outlier run, and only readable with one "
                              "input directory and few runs")
    parser.add_argument("--alpha", type=float, default=0.7, metavar="A",
                         help="Opacity of the run curves (default 0.7). Lower it "
                              "when many runs overlap, so that the density of the "
                              "band is visible rather than just its topmost curve")
    parser.add_argument("--show-theory", action="store_true",
                         help="Draw the bare (dashed) and the L=infinity "
                              "renormalized (dotted) exponential decay for each "
                              "directory, as a reference for the run curves")
    parser.add_argument("-o", "--output", type=Path, nargs="?", default=None,
                         const=AUTO_OUTPUT,
                         help="Save the plot to this file instead of showing it; "
                              "without an argument, save to figs/<first-input-dir-name>.pdf "
                              "(with -cmp<n> appended when several input dirs are given)")
    parser.add_argument("--xlim", type=float, nargs=2, default=None,
                         metavar=("XMIN", "XMAX"),
                         help="x-axis limits of the plot, in units of the bare "
                              "correlation time")
    parser.add_argument("--ylim", type=float, nargs=2, default=None,
                         metavar=("YMIN", "YMAX"),
                         help="y-axis limits of the plot")
    parser.add_argument("--xlog", action="store_true",
                         help="Use a logarithmic x-axis")
    parser.add_argument("--ylog", action="store_true",
                         help="Use a logarithmic y-axis")
    args = parser.parse_args()

    if args.output is AUTO_OUTPUT:
        stem = args.input_dirs[0].name.replace("avg-jp-time-corr-",
                                               "avg-jp-time-corr-runs-")
        if len(args.input_dirs) > 1:
            stem += f"-cmp{len(args.input_dirs) - 1}"
        args.output = Path("figs") / f"{stem}.pdf"
        args.output.parent.mkdir(exist_ok=True)

    single = len(args.input_dirs) == 1
    if args.label_runs and not single:
        raise SystemExit("--label-runs needs a single input directory: with "
                         "several, the runs of different directories would no "
                         "longer be told apart by color")
    # The mode index goes into the legend only when the y label
    # cannot carry it, i.e. when the directories do not share one.
    nk_varies = len({parse_obs_name(d)['nk']
                     for d in args.input_dirs}) > 1
    # One entry per run needs a legend beside the axes rather than inside
    # them, and the room for it has to come from a wider figure; constrained
    # layout is what fits an outside legend into the figure.
    if args.label_runs:
        fig, ax = plt.subplots(figsize=plot_style.figsize(width=2),
                               layout="constrained")
    else:
        fig, ax = plt.subplots()
    nks = []
    for input_dir in args.input_dirs:
        obs_name = parse_obs_name(input_dir)
        eta = obs_name["eta"]
        lam = obs_name["lam"]

        paths = sorted(input_dir.glob("*.dat"))
        if not paths:
            raise SystemExit(f"No correlator files found in {input_dir}")

        meta = read_header(paths[0])
        nks.append(meta["nk"])

        def eta_reg_uv(k2):
            x = k2/(lam*lam)
            if x > 1:
                return x - 1
            else:
                return 0

        k_hat = 2.0*np.sin(2 * np.pi * meta["nk"] / meta["nx"] * 0.5)
        damp = eta*(1+eta_reg_uv(k_hat**2)) / args.mass_density * k_hat**2
        # The time axis is scaled by the bare correlation time of the mode,
        # tau_bare = 1/damp = rho/(eta (1+eta_reg_uv) k_hat^2), so that the
        # bare exponential decays as exp(-t/tau_bare) whatever eta and k are.
        tau_bare = 1.0/damp

        nsites = meta["nx"] * meta["ny"] * meta["nz"]
        # Normalize to equilibrium correlator (i.e., value at t=0)
        C_eq = nsites*args.temp*args.mass_density

        coeff1, coeff2, coeff_inf = coefficients(3)
        etaR1 = np.sqrt(eta**2 + 2.0*coeff1*args.temp*args.mass_density*lam)
        etaR2 = np.sqrt(eta**2 + 2.0*coeff2*args.temp*args.mass_density*lam)
        etaR_inf = np.sqrt(eta**2 + 2.0*coeff_inf*args.temp*args.mass_density*lam)
        print("Renormalized eta: ", eta, " -> ", etaR1, "..", etaR2,
              " (L=inf: ", etaR_inf, ")")
        dampR_inf = etaR_inf*(1+eta_reg_uv(k_hat**2)) / args.mass_density * k_hat**2

        # One curve per run, over that run's own t. Only the real part, as in
        # plot_avg_jp_time_correlator.py.
        colors = run_colors(len(paths)) if args.label_runs else None
        # Without --label-runs the whole directory is one color, taken from
        # the property cycle the same way the averaged plot takes it, and
        # only the first run carries the legend entry for all of them.
        dir_color = None
        t_max = 0.0
        for i, path in enumerate(paths):
            t, re_part, im_part = np.loadtxt(path, unpack=True)
            if args.label_runs:
                label, color = run_label(path), colors[i]
            elif i == 0:
                label, color = (f"{legend_label(input_dir, with_nk=nk_varies)} "
                                f"({len(paths)} runs)"), None
            else:
                label, color = None, dir_color
            line, = ax.plot(t/tau_bare, re_part/C_eq, label=label, color=color,
                            alpha=args.alpha)
            if i == 0:
                dir_color = line.get_color()
            t_max = max(t_max, t[-1])

        if args.show_theory:
            # Drawn over the longest run, so the reference spans the data.
            t_theory = np.linspace(0.0, t_max, 500)
            # Black when there is nothing to tell apart, the directory's own
            # color otherwise; with --label-runs the runs have taken over the
            # colormap, so black is the only colour left that is not a run.
            color = "black" if single else dir_color
            first = input_dir is args.input_dirs[0]
            ax.plot(t_theory/tau_bare, np.exp(-damp*t_theory), "--",
                    color=color, alpha=0.7,
                    label=r"$\exp(-(\eta/\rho) \, \hat{\mathbf{k}}^2\, t)$"
                          if first else None)
            ax.plot(t_theory/tau_bare, np.exp(-dampR_inf*t_theory), ":",
                    color=color, alpha=0.7,
                    label=r"$\exp(-(\eta_R/\rho) \, \hat{\mathbf{k}}^2\, t)$, "
                          r"$L=\infty$" if first else None)

    ax.set_xlabel(r"$t / \tau$,  $\tau = \rho/(\eta \hat{\mathbf{k}}^2)$")
    if len(set(nks)) == 1:
        ylabel = r"$C(t,k=$" f"{nks[0]:.0f}" r"$\pi/N)/\rho T V$"
    else:
        ylabel = r"$C(t)/\rho T V$"
    ax.set_ylabel(ylabel)
    if args.xlim is not None:
        ax.set_xlim(*args.xlim)
    if args.xlog:
        ax.set_xscale('log')
    if args.ylim is not None:
        ax.set_ylim(*args.ylim)
    if args.ylog:
        ax.set_yscale('log')
    if args.label_runs:
        # Two columns from sixteen runs on, where one would run off the
        # bottom of a figure this shape.
        n_entries = len(ax.get_legend_handles_labels()[0])
        fig.legend(loc="outside right center", fontsize="x-small",
                   ncol=1 + (n_entries - 1)//16)
    else:
        ax.legend()
        fig.tight_layout(pad=0.2)

    if args.output is not None:
        fig.savefig(args.output)
    else:
        plt.show()


if __name__ == "__main__":
    main()
