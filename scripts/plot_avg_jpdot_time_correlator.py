#!/usr/bin/env python3
r"""Plot the time correlator of the time derivative of the current,
sum_T conj(djp/dt(t)) djp/dt(t+T), as a function of the time difference t,
averaged over several runs with an error band from their run-to-run
variation.

Reads the per-run correlator files written by
compute_avg_jpdot_time_correlator.py: one <run>.dat file per run in each
input directory, with columns time_diff, Re, Im and a header recording
nx, ny, nz, nk, dt for the given mode.

Each input directory is expected to be named as generated by
compute_avg_jpdot_time_correlator.py, e.g.
avg-jpdot-time-corr-Nx8Ny8Nz8dt0.1eta0.1Lam1.25nk7 (with an optional
trailing "x" for --no-ideal-step runs); the shear viscosity eta is parsed
from that name. With several directories, the real parts of all of them are
drawn into the same plot, each with its own theory curve in the same color.

The t axis is scaled by the bare correlation time of the mode,
tau = rho/(eta (1+eta_reg_uv) k_hat^2), exactly as in
plot_avg_jp_time_correlator.py. The correlator itself is made dimensionless
with the same tau, i.e. it is drawn as tau^2 C_jdot(t)/(rho T V), so that
curves from different eta and k can be compared directly: two time
derivatives cost two powers of tau relative to C(t)/(rho T V).

Unlike C(t), this correlator changes sign, and it is negative over almost
all of its range: for a mode relaxing as C(t) = C_eq exp(-Gamma |t|), the
correlator of the centred difference is exactly

    C_jdot(t) = [2 C(t) - C(t+2h) - C(|t-2h|)] / (4 h^2)

with h the snapshot spacing dt, which is positive only for t <= h (the
noise spike at equal times) and negative for t >= 2h, decaying as
-C_eq exp(-Gamma t) sinh^2(Gamma h)/h^2. What is plotted is therefore
-C_jdot, which is positive everywhere except at the first one or two
points; the files written by compute_avg_jpdot_time_correlator.py hold
C_jdot itself, only the figure is flipped. The same prediction, also
flipped, is drawn with --show-theory, for the bare and for the
renormalized eta. Note that it depends on h: the equal-time value grows
like 1/h as the snapshots are taken more finely, so compare directories at
equal dt, or look at the tail, which converges to
Gamma^2 C_eq exp(-Gamma t). A plain --ylog now keeps the tail and drops
only the equal-time spike; --symlog shows both.

--power-law adds a power law (Delta t/tau)^p through the data as a guide to
the eye, with p = -1/2 unless another exponent is given. Its amplitude is
matched to the data (the median of the data over t^p over the window set by
--power-law-range), so the line shows the slope, not an independent
prediction; on --ylog it is the straight line to compare the tail against."""

import argparse
import re
from fractions import Fraction
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

import plot_style
from rfrg_coefficients import coefficients

plot_style.use()

AUTO_OUTPUT = Path("<auto>")

FLOAT = r"[0-9.]+(?:[eE][+-]?[0-9]+)?"
OBS_NAME_RE = re.compile(
    rf"avg-jpdot-time-corr-Nx(?P<nx>\d+)Ny(?P<ny>\d+)Nz(?P<nz>\d+)"
    rf"dt(?P<dt>{FLOAT})eta(?P<eta>{FLOAT})Lam(?P<lam>{FLOAT})nk(?P<nk>\d+)(?P<suffix>x?)$"
)


def parse_obs_name(input_dir: Path) -> dict:
    m = OBS_NAME_RE.match(input_dir.name)
    if m is None:
        raise SystemExit(f"Cannot parse input directory name '{input_dir.name}': "
                         "expected the form avg-jpdot-time-corr-Nx8Ny8Nz8dt0.1eta0.1Lam1.25nk7")
    return {"nx": int(m["nx"]), "ny": int(m["ny"]), "nz": int(m["nz"]),
            "dt": float(m["dt"]), "eta": float(m["eta"]), "lam": float(m["lam"]),
            "nk": int(m["nk"])}


def lattice_label(nx: int, ny: int, nz: int) -> str:
    r"""LaTeX for the lattice size: $32^3$ for a cubic lattice, $32^2 \times 10$
    when one direction differs from the two others."""
    dims = (nx, ny, nz)
    if nx == ny == nz:
        return rf"${nx}^3$"
    for d in dims:
        if dims.count(d) == 2:
            odd = next(o for o in dims if o != d)
            return rf"${d}^2 \times {odd}$"
    return rf"${nx} \times {ny} \times {nz}$"


def dimension(nx: int, ny: int, nz: int) -> int:
    """Number of spatial dimensions of the lattice, i.e. the number of
    directions with more than one site: Nx32Ny1Nz32 is d = 2,
    Nx32Ny32Nz32 is d = 3."""
    return sum(1 for n in (nx, ny, nz) if n != 1)


def inverse_reynolds(eta: float, lam: float, d: int,
                     mass_density: float, temp: float) -> float:
    r"""Inverse Reynolds number 1/Re = \eta / \sqrt{\rho T \Lambda^{d-2}}."""
    return eta / np.sqrt(mass_density * temp * lam**(d - 2))


def legend_label(input_dir: Path, mass_density: float, temp: float) -> str:
    r"""Legend entry for one directory, e.g.
    "$32^3$, $1/\mathrm{Re} = 0.1118$, $a \Lambda = 0.4$, $n_k = 1$".

    The numbers are taken verbatim from the directory name, so the legend
    shows exactly what the run used, except for the viscosity, which is
    converted into the inverse Reynolds number
    1/Re = eta/sqrt(rho T Lambda^(d-2)) with d read off from the lattice
    size. The mode index is always shown, and --no-ideal-step runs are
    marked as such; without those, two directories differing only in nk (or
    in the trailing "x") would get the same legend entry."""
    m = OBS_NAME_RE.match(input_dir.name)
    nx, ny, nz = int(m["nx"]), int(m["ny"]), int(m["nz"])
    inv_re = inverse_reynolds(float(m["eta"]), float(m["lam"]),
                              dimension(nx, ny, nz), mass_density, temp)
    label = (f"{lattice_label(nx, ny, nz)}, "
             rf"$1/\mathrm{{Re}} = {inv_re:.4g}$, $a \Lambda = {m['lam']}$")
    label += rf", $n_k = {m['nk']}$"
    if m["suffix"] == "x":
        label += ", no ideal step"
    return label


def read_header(path: Path) -> dict:
    with open(path) as f:
        first_line = f.readline().lstrip("#").strip()
    return {key: float(value) for key, value in
            (item.split("=") for item in first_line.split())}


def exponent_label(exponent: float) -> str:
    r"""LaTeX for the exponent of the guide line, as the fraction it almost
    always is: -0.5 becomes -1/2, -1.5 becomes -3/2, -2.0 becomes -2."""
    frac = Fraction(exponent).limit_denominator(16)
    if float(frac) != exponent:
        return f"{exponent:g}"
    if frac.denominator == 1:
        return f"{frac.numerator}"
    return rf"{frac.numerator}/{frac.denominator}"


def power_law_guide(t_scaled: np.ndarray, y: np.ndarray, exponent: float,
                    window: tuple) -> tuple:
    """A line proportional to t^exponent, placed on top of the data.

    The amplitude is the median of y/t^exponent over the window, not a fit:
    the tail of this correlator crosses zero repeatedly once it has decayed
    into the noise, and the points just above a crossing would drag a
    least-squares amplitude in log-log arbitrarily far down. The median
    ignores them, which is what a guide to the eye should do. Returns the
    (t, guide) pair to draw, or (None, None) when the window holds no
    positive points."""
    lo, hi = window
    selected = (t_scaled > 0) & (y > 0) & (t_scaled >= lo) & (t_scaled <= hi)
    if selected.sum() < 2:
        return None, None
    amplitude = np.median(y[selected] / t_scaled[selected]**exponent)
    # Drawn over the whole window rather than only at the points that went
    # into the median, so that the line does not break up where the data
    # dips below zero.
    t_line = np.geomspace(t_scaled[selected].min(), t_scaled[selected].max(), 200)
    return t_line, amplitude * t_line**exponent


def jdot_correlator(time_diff: np.ndarray, damp: float, c_eq: float,
                    h: float) -> np.ndarray:
    """The derivative correlator of a mode relaxing as C(t) = c_eq exp(-damp |t|),
    as compute_avg_jpdot_time_correlator.py measures it.

    That script differentiates with np.gradient, i.e. with the centred
    difference (j(t+h) - j(t-h))/(2h) at the snapshot spacing h, so the
    measured correlator is the second difference of C at spacing 2h, not the
    continuum -C''(t). C(-t) = C(t) for this ansatz, hence the |t - 2h|."""
    def c(t):
        return c_eq * np.exp(-damp * np.abs(t))
    return (2 * c(time_diff) - c(time_diff + 2 * h)
            - c(np.abs(time_diff - 2 * h))) / (4 * h**2)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input_dirs", type=Path, nargs="+",
                         help="One or more directories containing the *.dat correlator "
                              "files written by compute_avg_jpdot_time_correlator.py, named "
                              "like avg-jpdot-time-corr-Nx8Ny8Nz8dt0.1eta0.1Lam1.25nk7 (eta is "
                              "parsed from the name); all are drawn into the same plot")
    parser.add_argument("--mass-density", type=float, default=1.0, help="Mass density")
    parser.add_argument("--temp", type=float, default=1.0, help="Temperature")
    parser.add_argument("-o", "--output", type=Path, nargs="?", default=None,
                         const=AUTO_OUTPUT,
                         help="Save the plot to this file instead of showing it; "
                              "without an argument, save to figs/<first-input-dir-name>.pdf "
                              "(with -cmp<n> appended when several input dirs are given)")
    parser.add_argument("--xlim", type=float, nargs=2, default=None,
                         metavar=("XMIN", "XMAX"),
                         help="x-axis limits of the plot, in units of the bare "
                              "correlation time")
    parser.add_argument("--ylim", type=float, nargs=2, default=None,
                         metavar=("YMIN", "YMAX"),
                         help="y-axis limits of the plot")
    parser.add_argument("--xlog", action="store_true",
                         help="Use a logarithmic x-axis")
    parser.add_argument("--ylog", action="store_true",
                         help="Use a logarithmic y-axis; -C_jdot is positive away from "
                              "the equal-time spike, so this shows the tail and drops "
                              "the first one or two points, use --symlog to keep them")
    parser.add_argument("--symlog", action="store_true",
                         help="Use a symmetric logarithmic y-axis, which resolves both "
                              "the positive tail and the negative equal-time spike")
    parser.add_argument("--show-theory", action="store_true",
                         help="Draw the exponential-relaxation prediction for the bare "
                              "(dashed) and the renormalized (dotted) shear viscosity, "
                              "discretized the same way the data is")
    parser.add_argument("--power-law", type=float, nargs="?", default=None,
                         const=-0.5, metavar="EXPONENT",
                         help="Draw a power law (Delta t/tau)^EXPONENT through the "
                              "data as a guide to the eye (dash-dotted); without an "
                              "argument, the exponent is -1/2. The amplitude is the "
                              "median of the data over t^EXPONENT, so the line lands "
                              "on the curve; restrict where with --power-law-range")
    parser.add_argument("--power-law-range", type=float, nargs=2, default=None,
                         metavar=("TMIN", "TMAX"),
                         help="Window in Delta t/tau the power law is matched to the "
                              "data over, and drawn across (default: --xlim if given, "
                              "else every point where -C_jdot is positive)")
    args = parser.parse_args()

    if args.output is AUTO_OUTPUT:
        stem = args.input_dirs[0].name
        if len(args.input_dirs) > 1:
            stem += f"-cmp{len(args.input_dirs) - 1}"
        args.output = Path("figs") / f"{stem}.pdf"
        args.output.parent.mkdir(exist_ok=True)

    fig, ax = plt.subplots()
    for input_dir in args.input_dirs:
        obs_name = parse_obs_name(input_dir)
        eta = obs_name["eta"]
        lam = obs_name["lam"]

        paths = sorted(input_dir.glob("*.dat"))
        if not paths:
            raise SystemExit(f"No correlator files found in {input_dir}")

        meta = read_header(paths[0])

        correlators = []
        time_diff = None
        for path in paths:
            t, re_part, im_part = np.loadtxt(path, unpack=True)
            if time_diff is None:
                time_diff = t
            correlators.append(re_part + 1j * im_part)

        n_min = min(len(c) for c in correlators)
        correlators = np.stack([c[:n_min] for c in correlators])
        time_diff = time_diff[:n_min]

        mean = correlators.mean(axis=0)
        n_runs = len(correlators)
        if n_runs > 1:
            # Standard error of the mean, not the run-to-run standard deviation:
            # the latter reflects the spread from the Langevin noise itself and
            # does not shrink as more runs are added, while the SEM quantifies
            # the uncertainty on the estimated mean correlator.
            sem_re = correlators.real.std(axis=0, ddof=1) / np.sqrt(n_runs)
        else:
            sem_re = np.zeros(n_min)

        def eta_reg_uv(k2):
            x = k2/(lam*lam)
            if x > 1:
                return x - 1
            else:
                return 0

        k_hat = 2.0*np.sin(2 * np.pi * meta["nk"] / meta["nx"] * 0.5)
        damp = eta*(1+eta_reg_uv(k_hat**2)) / args.mass_density * k_hat**2
        # The time axis is scaled by the bare correlation time of the mode,
        # tau_bare = 1/damp = rho/(eta (1+eta_reg_uv) k_hat^2), so that the
        # bare exponential decays as exp(-t/tau_bare) whatever eta and k are.
        tau_bare = 1.0/damp
        t_scaled = time_diff/tau_bare

        nsites = meta["nx"] * meta["ny"] * meta["nz"]
        # Normalize to the equilibrium correlator (the value C(t=0) of the
        # correlator itself), times tau^2 for the two time derivatives, so
        # that the normalized tail is O(1) for every eta and k. The minus
        # sign flips the curve to -C_jdot, which is positive everywhere but
        # at the equal-time spike; it sits in the normalization so that the
        # data, its error band and both theory curves cannot get out of sync.
        C_eq = nsites*args.temp*args.mass_density
        norm = -tau_bare**2 / C_eq

        coeff1, coeff2, coeff_inf = coefficients(3)
        etaR1 = np.sqrt(eta**2 + 2.0*coeff1*args.temp*args.mass_density*lam)
        etaR2 = np.sqrt(eta**2 + 2.0*coeff2*args.temp*args.mass_density*lam)
        etaR_inf = np.sqrt(eta**2 + 2.0*coeff_inf*args.temp*args.mass_density*lam)
        print("Renormalized eta: ", eta, " -> ", etaR1, "..", etaR2,
              " (L=inf: ", etaR_inf, ")")

        dampR_inf = etaR_inf*(1+eta_reg_uv(k_hat**2)) / args.mass_density * k_hat**2

        label = legend_label(input_dir, args.mass_density, args.temp)
        line, = ax.plot(t_scaled, mean.real*norm, label=label)
        ax.fill_between(t_scaled, (mean.real - sem_re)*norm,
                        (mean.real + sem_re)*norm,
                        color=line.get_color(), alpha=0.3)

        if args.show_theory:
            # The snapshot spacing the derivative was taken at; the prediction
            # depends on it, so it is read from the correlator header rather
            # than from the time axis.
            h = meta["dt"]
            theory = jdot_correlator(time_diff, damp, C_eq, h)
            theoryR_inf = jdot_correlator(time_diff, dampR_inf, C_eq, h)
            ax.plot(t_scaled, theory*norm, "--", color=line.get_color(),
                    alpha=0.7)
            ax.plot(t_scaled, theoryR_inf*norm, ":", color=line.get_color(),
                    alpha=0.7)

        if args.power_law is not None:
            window = (args.power_law_range if args.power_law_range is not None
                      else args.xlim if args.xlim is not None
                      else (0.0, np.inf))
            t_line, guide = power_law_guide(t_scaled, mean.real*norm,
                                            args.power_law, window)
            if t_line is None:
                print(f"warning: {input_dir}: no positive points in the "
                      "power-law window, drawing no guide line")
            else:
                first = input_dir is args.input_dirs[0]
                ax.plot(t_line, guide, "-.", color=line.get_color(), alpha=0.7,
                        label=(rf"$\propto (\Delta t/\tau)^{{{exponent_label(args.power_law)}}}$"
                               if first else None))

    ax.set_xlabel(r"$\Delta t / \tau$,  $\tau = \rho/(\eta \hat{\mathbf{k}}^2)$")
    ax.set_ylabel(r"$-\tau^2 C_{\dot{j}}(\Delta t,k)/\rho T V$")
    if args.xlim is not None:
        ax.set_xlim(*args.xlim)
    if args.xlog:
        ax.set_xscale('log')
    if args.ylim is not None:
        ax.set_ylim(*args.ylim)
    if args.ylog:
        ax.set_yscale('log')
    if args.symlog:
        ax.set_yscale('symlog', linthresh=1e-3)
    ax.legend()
    fig.tight_layout(pad=0.2)

    if args.output is not None:
        fig.savefig(args.output)
    else:
        plt.show()


if __name__ == "__main__":
    main()
